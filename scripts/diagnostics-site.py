#!/usr/bin/env python3
"""Generate/check the website diagnostic reference from the normative specification table."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "docs/specifications/diagnostics.md"
OUT = ROOT / "website/src/data/diagnostics.ts"
rows = []
for line in SPEC.read_text().splitlines():
    if not re.match(r'^\| [EWI]\d{3} \|', line):
        continue
    cells = [cell.strip().strip('`') for cell in line.strip('|').split(' | ')]
    if len(cells) != 6:
        raise SystemExit(f"malformed diagnostic row: {line}")
    code, severity, condition, ja, en, action = cells
    rows.append(dict(code=code, severity=severity, condition=condition,
                     ja=ja, en=en, action=action))

if len(rows) != 76 or len({row['code'] for row in rows}) != len(rows):
    raise SystemExit(f"expected 76 unique diagnostic codes, found {len(rows)}")
result = "// Generated by scripts/diagnostics-site.py from docs/specifications/diagnostics.md.\n"
result += "// Run `python3 scripts/diagnostics-site.py --check` to verify coverage.\n"
result += "export const diagnostics = " + json.dumps(rows, ensure_ascii=False, indent=2) + " as const;\n"
if '--check' in sys.argv:
    if not OUT.exists() or OUT.read_text() != result:
        raise SystemExit(f"{OUT.relative_to(ROOT)} is out of sync; run python3 scripts/diagnostics-site.py")
else:
    OUT.write_text(result)
