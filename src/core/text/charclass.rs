//! 日本語の文字種判定（唯一の置き場）。
//!
//! ここに並ぶ述語は、どれも「その文字が日本語の側か」を答えるが、**返す範囲は意図的に違う**。
//! 使う側の要求が違うためで、ひとつに揃えるかどうかは仕様の判断である（半角カナ・拡張 A・
//! 互換漢字を日本語に数えるか、が争点になる）。したがって、このモジュールで揃えてよいのは
//! **置き場所だけ**で、範囲を動かすときは仕様側の根拠を先に用意する。
//!
//! 判定の性格は 3 つに分かれる。
//!
//! - **範囲を明示するもの**（[`classify`] / [`is_ruby_base_kanji`] / [`is_body_japanese`] /
//!   [`is_kana`] / [`is_halfwidth_katakana`]）: 仕様や字句規則が対象を列挙しているので、
//!   範囲そのものが仕様である。
//! - **文字プロパティに委ねるもの**（[`is_word_char`]）: 「語らしい文字か」だけを答えれば
//!   よい場面（診断の語の判定）で使う。スクリプトを問わないので、仮名・漢字のほか
//!   ラテン文字・キリル文字・ハングル・〇 付き数字も語になる。
//! - **指紋として使うもの**（[`is_halfwidth_katakana`] / [`is_kana`]）: 文字化けの入口と
//!   出口の判定で、「この文字列は日本語として読めるか」を粗く見る。

/// 文字種（§6.2.6「漢字・カタカナ・ひらがな・英数字の文字種境界」）。
///
/// ASCII の英数字と全角の英数字は**同じクラス**にする（`Ｍ0137` と `M0137` を別の
/// 形態素に割らないため）。長音符 `ー`（U+30FC）はカタカナ側に入れる（`コーヒー` を
/// 1 つの形態素として扱う）。それ以外（記号・約物）は [`CharClass::Other`]。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CharClass {
    /// 漢字（`々` `〆` を含む）。
    Kanji,
    /// カタカナ（半角カナ・長音符・濁点を含む）。
    Katakana,
    /// ひらがな（`ゝ` `ゞ` を含む）。
    Hiragana,
    /// 英数字（ASCII と全角）。
    Alphanumeric,
    /// それ以外（記号・約物）。
    Other,
}

/// [`CharClass`] を返す（§6.2.6 の形態素境界が使う）。
///
/// 拡張 A（U+3400–U+4DBF）は [`CharClass::Other`] になる。§6.2.6 が列挙するのは
/// 「漢字・カタカナ・ひらがな・英数字」で、拡張 A を含むとは書いていないため。
pub fn classify(c: char) -> CharClass {
    match c {
        '\u{3041}'..='\u{3096}' | '\u{309D}'..='\u{309F}' => CharClass::Hiragana,
        '\u{30A1}'..='\u{30FA}' | '\u{30FC}'..='\u{30FE}' | '\u{FF66}'..='\u{FF9F}' => {
            CharClass::Katakana
        }
        '\u{3005}' | '\u{3006}' | '\u{4E00}'..='\u{9FFF}' | '\u{F900}'..='\u{FAFF}' => {
            CharClass::Kanji
        }
        '\u{FF10}'..='\u{FF19}' | '\u{FF21}'..='\u{FF3A}' | '\u{FF41}'..='\u{FF5A}' => {
            CharClass::Alphanumeric
        }
        c if c.is_ascii_alphanumeric() => CharClass::Alphanumeric,
        _ => CharClass::Other,
    }
}

/// ルビの親文字になれる漢字か（§5.2.1 `kanji_run`）。
///
/// CJK 統合漢字 U+4E00–U+9FFF・拡張 A U+3400–U+4DBF・互換漢字 U+F900–U+FAFF。
/// [`classify`] と違い**拡張 A を含み**、繰返し字（[`is_kanji_mark`]）は含まない。
/// `kanji_run` の範囲は仕様書に定義が無いのでここで決めた（`docs/history.md` B-33）。
pub fn is_ruby_base_kanji(c: char) -> bool {
    matches!(c, '\u{4E00}'..='\u{9FFF}' | '\u{3400}'..='\u{4DBF}' | '\u{F900}'..='\u{FAFF}')
}

/// 繰返し字（`々` U+3005・`〻` U+303B）か。
///
/// `人々《ひとびと》` のように漢字列に含める（§5.2.1）。
pub fn is_kanji_mark(c: char) -> bool {
    matches!(c, '\u{3005}' | '\u{303B}')
}

/// 本文の言語判定で「日本語」に数える文字か（§7.2.2）。
///
/// ひらがな・カタカナ・長音符・CJK 統合漢字だけ。**半角カナ・拡張 A・互換漢字・
/// `々` は数えない**（仕様 §7.2.2 は「本文の文字種で決める」とだけ書き、対象を
/// 列挙していないため、実装が決めた範囲をここに固定している）。
pub fn is_body_japanese(c: char) -> bool {
    matches!(c, '\u{3041}'..='\u{3096}' | '\u{30A1}'..='\u{30F6}' | '\u{30FC}' | '\u{4E00}'..='\u{9FFF}')
}

/// 本文の言語判定で「ラテン」に数える文字か（§7.2.2）。
///
/// ASCII の英字だけ。他のスクリプト（キリル文字など）はどちらにも数えない。
pub fn is_body_latin(c: char) -> bool {
    c.is_ascii_alphabetic()
}

/// 診断の「語」として数えてよい文字か（§9.4.4）。
///
/// 文字プロパティで判定する（[`classify`] の [`CharClass::Other`] の否定とは範囲が違う）。
/// 仮名・漢字（拡張 A を含む）・ハングルのほか、ラテン文字や〇 付き数字も語になる。
/// 標点（`、` `。` `「` など）と空白は語にならない。
pub fn is_word_char(c: char) -> bool {
    c.is_alphanumeric()
        || ('\u{3040}'..='\u{30FF}').contains(&c)
        || ('\u{3400}'..='\u{9FFF}').contains(&c)
        || ('\u{AC00}'..='\u{D7AF}').contains(&c)
}

/// 文字化けの修復候補が「日本語として読める」かの判定に使うかなか（§14.6.1）。
///
/// ひらがな U+3041–U+3096 とカタカナ U+30A1–U+30FA。長音符と半角カナは含まない。
pub fn is_kana(c: char) -> bool {
    matches!(c, '\u{3041}'..='\u{3096}' | '\u{30A1}'..='\u{30FA}')
}

/// 半角カタカナ（U+FF66–U+FF9D）か（§14.6.1 の文字化けの指紋）。
///
/// 濁点・半濁点だけの `ﾞ` `ﾟ`（U+FF9E–U+FF9F）は含まない。
pub fn is_halfwidth_katakana(c: char) -> bool {
    ('\u{FF66}'..='\u{FF9D}').contains(&c)
}
