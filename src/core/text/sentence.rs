//! 文の区切り（`。` `！` `？`）。
//!
//! 字句の単位ではなく**読みの単位**で、使うのは執筆支援の W 系診断（§9.4.4）と
//! 字数の見積もりである。区切りの規則は「文末記号の直後で切る」だけで、`…` は
//! 文末にしない。
//!
//! 役割語（§6.5.2）の文はこれと**別の規則**を持つ（`…` `!` `?` も文末にし、発話の
//! 頭にある文末記号の連続は次の文に含める）。両者は仕様上ちがう単位なので、
//! ここへ寄せずに [`crate::core::resolve::role_language::sentences`] を残している。

use std::ops::Range;

/// W 系（§9.4.4）の文末記号。
///
/// `…` は含めない（§7.2.3 と §9.4.4 が `。！？` で区切ると明記している）。
pub const STOPS: &[char] = &['。', '！', '？'];

/// 文に切り、`(本文中の byte 範囲, 文)` を読み順に返す。
///
/// 文末記号は**文に含める**（`str::split_inclusive` と同じ）。文末記号が 1 つも無い
/// 本文は、全体が 1 文として返る。空の本文は何も返さない。
///
/// 範囲は連結した本文の中の位置なので、節の中の複数行を `\n` で連結してから渡せば
/// 「改行は連続を切らない」がそのまま成り立つ（§7.2.3）。
pub fn split(text: &str) -> impl Iterator<Item = (Range<usize>, &str)> + '_ {
    let mut at = 0usize;
    text.split_inclusive(STOPS).map(move |sentence| {
        let start = at;
        at += sentence.len();
        (start..at, sentence)
    })
}
